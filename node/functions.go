package node

import (
	"bytes"
	"io"

	"github.com/jpl-au/fluent"
)

// FuncsComponent enables dynamic content generation of multiple nodes.
// The function is called during rendering to generate the actual node content.
// This is useful for generating lists of items, e.g. from a loop.
//
// Nil nodes are safely ignored - any nil nodes in the returned slice will be skipped.
//
// Usage:
//
//	Funcs(func() []Node {
//	    nodes := []Node{}
//	    for _, item := range items {
//	        nodes = append(nodes, li.Text(item.Name))
//	    }
//	    return nodes
//	})
type FuncsComponent struct {
	fn func() []Node
}

// Funcs creates a new function component that will call the provided function
// during rendering to generate a slice of nodes. It is the plural form of Func —
// use Func when the function returns a single Node, and Funcs when it returns a slice.
func Funcs(fn func() []Node) *FuncsComponent {
	return &FuncsComponent{
		fn: fn,
	}
}

// Render generates the HTML representation by calling the function.
// If a writer is provided, the output is written to it and nil is returned.
// If no writer is provided, the output is returned as a byte slice.
func (f *FuncsComponent) Render(w ...io.Writer) []byte {
	buf := fluent.NewBuffer()
	f.RenderBuilder(buf)

	if len(w) > 0 && w[0] != nil {
		_, _ = buf.WriteTo(w[0])
		fluent.PutBuffer(buf)
		return nil
	}
	return buf.Bytes()
}

// RenderBuilder writes the HTML representation directly to a buffer.
// Calls the function to get the actual nodes and renders them.
// Nil nodes are safely ignored.
func (f *FuncsComponent) RenderBuilder(buf *bytes.Buffer) {
	if f.fn != nil {
		nodes := f.fn()
		for _, node := range nodes {
			if node != nil {
				node.RenderBuilder(buf)
			}
		}
	}
}

// IsDynamic returns true — function components always contain dynamic content
// because their output depends on a function call at render time.
func (f *FuncsComponent) IsDynamic() bool {
	return true
}

// DynamicKey returns an empty string — function components do not carry tracking keys.
func (f *FuncsComponent) DynamicKey() string {
	return ""
}

// Nodes evaluates the function and returns its output. Returning an empty
// slice would hide any keyed children from tree walkers, which breaks the
// Differ's ability to detect patches and structural changes for elements
// generated by function components.
func (f *FuncsComponent) Nodes() []Node {
	if f.fn != nil {
		return f.fn()
	}
	return nil
}
